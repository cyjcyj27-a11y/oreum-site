/* 그레고리력 → 율리우스 적일 */
function lunarJDN(y, m, d) {
  var a = Math.floor((14 - m) / 12);
  var yy = y + 4800 - a;
  var mm = m + 12 * a - 3;
  return d + Math.floor((153 * mm + 2) / 5) + 365 * yy
       + Math.floor(yy / 4) - Math.floor(yy / 100) + Math.floor(yy / 400) - 32045;
}

/* 한 음력 해의 달 목록 → [{ m:월번호, leap:윤달, days:일수, start:시작JDN }] */
function lunarMonthsOf(lyear) {
  var row = LUNAR_TABLE[lyear - LUNAR_START_YEAR];
  if (!row) return null;
  var p = row.split(',');
  var start = +p[0], leap = +p[1], bits = +p[2], count = +p[3];
  var list = [], num = 1, cur = start, usedLeap = false;
  for (var j = 0; j < count; j++) {
    var days = ((bits >> (count - 1 - j)) & 1) ? 30 : 29;
    var thisNum = num, thisLeap = false;
    if (leap > 0 && !usedLeap && num === leap + 1) {
      /* 윤N월은 N월 바로 다음 자리에 온다 */
      thisNum = leap; thisLeap = true; usedLeap = true;
    } else {
      num++;
    }
    list.push({ m: thisNum, leap: thisLeap, days: days, start: cur });
    cur += days;
  }
  return list;
}

/* 양력 → 음력. { year, month, day, leap, monthDays } 또는 null */
function solarToLunar(y, m, d) {
  var j = lunarJDN(y, m, d);
  for (var ly = y; ly >= y - 1; ly--) {
    var ms = lunarMonthsOf(ly);
    if (!ms) continue;
    var last = ms[ms.length - 1];
    if (j < ms[0].start || j >= last.start + last.days) continue;
    for (var i = 0; i < ms.length; i++) {
      if (j >= ms[i].start && j < ms[i].start + ms[i].days) {
        return { year: ly, month: ms[i].m, day: j - ms[i].start + 1,
                 leap: ms[i].leap, monthDays: ms[i].days };
      }
    }
  }
  return null;
}

