function maskLevel(god) {
  // 나를 드러내는 기운 vs 나를 누르고 다듬는 기운
  // 지장간 가중 개수(소수)라서 표시용으로 소수 1자리로 반올림한다
  var 나 = Math.round(((god['비겁'] || 0) + (god['식상'] || 0)) * 10) / 10;
  var 사회 = Math.round(((god['관성'] || 0) + (god['인성'] || 0)) * 10) / 10;
  var 차 = Math.round((사회 - 나) * 10) / 10;   // 클수록 사회화 쪽
  for (var i = 0; i < MASK_LEVELS.length; i++) {
    if (차 <= MASK_LEVELS[i].max) {
      return { level: MASK_LEVELS[i], 나: 나, 사회: 사회, 차: 차 };
    }
  }
  return { level: MASK_LEVELS[MASK_LEVELS.length - 1], 나: 나, 사회: 사회, 차: 차 };
}

