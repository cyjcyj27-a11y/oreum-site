/* 음력 → 양력. 윤달이면 leap = true. 없는 날이면 null */
function u27LunarToSolar(ly, lm, ld, leap) {
  var ms = (typeof lunarMonthsOf === 'function') ? lunarMonthsOf(ly) : null;
  if (!ms) return null;
  for (var i = 0; i < ms.length; i++) {
    var x = ms[i];
    if (x.m === lm && !!x.leap === !!leap) {
      if (ld < 1 || ld > x.days) return null;
      var j = x.start + ld - 1;                         // JDN → 그레고리력
      var a = j + 32044, b = Math.floor((4 * a + 3) / 146097), c = a - Math.floor(146097 * b / 4);
      var d = Math.floor((4 * c + 3) / 1461), e = c - Math.floor(1461 * d / 4), m = Math.floor((5 * e + 2) / 153);
      return { year: 100 * b + d - 4800 + Math.floor(m / 10), month: m + 3 - 12 * Math.floor(m / 10),
               day: e - Math.floor((153 * m + 2) / 5) + 1 };
    }
  }
  return null;
}


