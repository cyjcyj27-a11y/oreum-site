function u27Months() {
  var T = SAJU_TERMS[2027], T2 = SAJU_TERMS[2028];
  var starts = [T[1], T[2], T[3], T[4], T[5], T[6], T[7], T[8], T[9], T[10], T[11], T2[0]];
  var ends = [T[2], T[3], T[4], T[5], T[6], T[7], T[8], T[9], T[10], T[11], T2[0], T2[1]];
  var names = ['입춘', '경칩', '청명', '입하', '망종', '소서', '입추', '백로', '한로', '입동', '대설', '소한'];
  var stemStart = ((U27.stem % 5) * 2 + 2) % 10;       // 오호둔 — 정년 인월은 임인
  var out = [];
  for (var i = 0; i < 12; i++) {
    var e = new Date(i === 10 || i === 11 ? 2028 : 2027, ends[i][0] - 1, ends[i][1] - 1);
    out.push({
      idx: i,
      term: names[i],
      from: { y: i === 11 ? 2028 : 2027, m: starts[i][0], d: starts[i][1] },
      to: { y: e.getFullYear(), m: e.getMonth() + 1, d: e.getDate() },
      stem: (stemStart + i) % 10,
      branch: (2 + i) % 12
    });
  }
  return out;
}

